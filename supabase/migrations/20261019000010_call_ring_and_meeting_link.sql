-- CarePoint: incoming-call ringing, and a shared Jitsi meeting link.
--
-- Two features, one migration, because both change the same two tables.
--
-- 1. RINGING. Today the only way to reach the other side is for them to be
--    staring at the right screen. `call_signals` gains a 'ring' kind so the
--    caller can announce itself on the peer's open page in real time. Ring
--    rows carry no session description — they are a knock on the door, and
--    the offer/answer pair that follows still does the WebRTC work. The CHECK
--    on `kind` is widened rather than replaced so a mis-typed kind is still
--    rejected by the database.
--
-- 2. MEETING LINK. A fallback for when peer-to-peer WebRTC cannot connect
--    (a symmetric NAT has no TURN relay to fall back to, and the room is
--    STUN-only by design). Either participant generates a Jitsi room once,
--    the column stores it, and both sides read the same row — so "sharing"
--    is just persistence, not a message that could be lost.
--
-- Both writes are funneled through an RPC: patients have no UPDATE grant on
-- appointments, and handing them one to set a link would also let them set
-- `status`. The function updates exactly one column, and only for a
-- participant.

-- ---------------------------------------------------------------------------
-- 1. meeting_url on appointments
-- ---------------------------------------------------------------------------

alter table public.appointments
  add column if not exists meeting_url text;

comment on column public.appointments.meeting_url is
  'Shared Jitsi room for this appointment; set once by either participant.';

-- ---------------------------------------------------------------------------
-- 2. set_appointment_meeting_link: the only way to write the column
-- ---------------------------------------------------------------------------

create or replace function public.set_appointment_meeting_link(
  p_appointment_id uuid,
  p_url            text
) returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_app   public.appointments%rowtype;
  v_title text := 'Meeting room ready';
  v_body  text;
begin
  -- Shape-checked so the column cannot be turned into an open redirect or a
  -- phishing target: this app only ever mints meet.jit.si rooms.
  if p_url is null or p_url !~ '^https://meet\.jit\.si/MamaDoc-[A-Za-z0-9-]{8,160}$' then
    raise exception 'that is not a CarePoint meeting link';
  end if;

  update public.appointments
     set meeting_url = p_url
   where id = p_appointment_id
     and status <> 'cancelled'
     and (patient_id = auth.uid() or doctor_id = auth.uid())
  returning * into v_app;

  if not found then
    -- Either it is not my appointment, or it was cancelled while I typed.
    raise exception 'this appointment cannot take a meeting link';
  end if;

  -- Shared automatically with BOTH sides: the URL sits on the appointment row
  -- both can read, and a notification carries it into each person's toast
  -- stack and notification bell — generated by the patient, the doctor is
  -- told; generated by the doctor, the patient is told. SECURITY DEFINER
  -- because no client holds an INSERT grant on notifications (migration
  -- 0004): users still cannot forge messages to each other.
  v_body := 'A shared room was created for this appointment: ' || p_url
         || ' — open the appointment and tap OPEN MEETING to join.';

  insert into public.notifications (recipient_id, appointment_id, kind, title, body)
  values (v_app.patient_id, v_app.id, 'meeting_link', v_title, v_body),
         (v_app.doctor_id,  v_app.id, 'meeting_link', v_title, v_body);
end;
$$;

revoke all on function public.set_appointment_meeting_link(uuid, text) from public, anon;
grant execute on function public.set_appointment_meeting_link(uuid, text) to authenticated;

-- ---------------------------------------------------------------------------
-- 3. 'ring' is a legal call signal
-- ---------------------------------------------------------------------------

-- Drop whatever check constraint covers `kind` — the default name is
-- call_signals_kind_check, but scanning keeps this correct if the column
-- was ever re-created under another name.
do $$
declare
  v_con record;
begin
  for v_con in
    select conname
      from pg_constraint
     where conrelid = 'public.call_signals'::regclass
       and contype = 'c'
       and pg_get_constraintdef(oid) ilike '%kind%'
  loop
    execute format('alter table public.call_signals drop constraint %I', v_con.conname);
  end loop;
end;
$$;

alter table public.call_signals
  add constraint call_signals_kind_check
  check (kind in ('offer', 'answer', 'end', 'ring'));

-- ---------------------------------------------------------------------------
-- 4. Realtime for the two tables these features watch
-- 0004 published `notifications`; ring rows and meeting-link updates arrive
-- as postgres_changes events, so both tables have to be in the publication.
-- `alter publication ... add table` errors when the table is already a
-- member, hence the guarded blocks.
-- ---------------------------------------------------------------------------

do $$
begin
  alter publication supabase_realtime add table public.call_signals;
exception when duplicate_object then
  null;
end;
$$;

do $$
begin
  alter publication supabase_realtime add table public.appointments;
exception when duplicate_object then
  null;
end;
$$;
